"""Builds files/lab2-methodical.docx. Run once; the DOCX is committed together with this script."""
from pathlib import Path
from docx import Document

VARIANTS = [
    (1, 'x^3 - x - 1', '[1; 2]', '1e-5'),
    (2, 'cos(x) - x', '[0; 1]', '1e-6'),
    (3, 'x^3 - 2x - 5', '[2; 3]', '1e-6'),
    (4, 'e^x - 3x', '[0; 1]', '1e-5'),
    (5, 'ln(x) + x - 2', '[1; 2]', '1e-6'),
]

d = Document()
d.add_heading('Лабораторна робота №2', level=1)
d.add_heading('Чисельне розв’язання нелінійних рівнянь', level=2)
d.add_paragraph('Мета роботи: опанувати методи половинного ділення (бісекції) та Ньютона (дотичних) '
                'для знаходження кореня рівняння f(x) = 0 на заданому відрізку з заданою точністю.')
d.add_heading('Короткі теоретичні відомості', level=2)
d.add_paragraph('Метод бісекції. Якщо f(a)·f(b) < 0, корінь лежить на [a; b]. На кожній ітерації обчислюють '
                'c = (a + b) / 2 і залишають ту половину відрізка, на кінцях якої функція має різні знаки. '
                'Ітерації припиняють, коли довжина відрізка стає меншою за ε.')
d.add_paragraph('Метод Ньютона. Починаючи з x0, обчислюють x(k+1) = x(k) − f(x(k)) / f′(x(k)). '
                'Ітерації припиняють, коли |x(k+1) − x(k)| < ε. Похідну f′(x) знаходять аналітично. '
                'Початкове наближення x0 — той кінець відрізка, де f(x)·f″(x) > 0.')
d.add_heading('Порядок виконання', level=2)
for line in [
    'Написати програму мовою JavaScript (Node.js) без сторонніх бібліотек, що реалізує обидва методи.',
    'Для свого варіанта знайти корінь кожним методом із точністю ε і підрахувати кількість ітерацій.',
    'Зберегти результати у файл roots.json: масив із двох об’єктів з полями method ("bisection" або "newton"), '
    'root, iterations, f_root (значення функції в знайденому корені).',
    'Перевірити результати: підставити корінь у рівняння, порівняти корені двох методів між собою.',
    'Порівняти кількість ітерацій методів і зробити висновок про швидкість збіжності.',
]:
    d.add_paragraph(line, style='List Number')
d.add_heading('Варіанти завдань', level=2)
t = d.add_table(rows=1, cols=4)
t.style = 'Table Grid'
for cell, text in zip(t.rows[0].cells, ['Варіант', 'Рівняння f(x) = 0', 'Відрізок', 'Точність ε']):
    cell.text = text
for row in VARIANTS:
    cells = t.add_row().cells
    for cell, text in zip(cells, row):
        cell.text = str(text)
d.add_heading('Зміст звіту', level=2)
d.add_paragraph('Титульна сторінка, мета, короткі теоретичні відомості, умова свого варіанта, текст програми, '
                'таблиця результатів (корінь, f(корінь), кількість ітерацій для кожного методу), висновки.')
d.add_heading('Контрольні запитання', level=2)
for q in ['Яка умова існування кореня на відрізку?', 'Як оцінити кількість ітерацій методу бісекції наперед?',
          'Чому метод Ньютона зазвичай збігається швидше?', 'Коли метод Ньютона може не збігтися?']:
    d.add_paragraph(q, style='List Bullet')
out = Path(__file__).parent / 'files' / 'lab2-methodical.docx'
out.parent.mkdir(exist_ok=True)
d.save(out)
print(out)
